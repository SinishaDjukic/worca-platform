// Generates migrations/0001_auth.sql: the Better Auth tables for our exact plugin set, created
// against an in-memory SQLite (Better Auth introspects a live database to diff).
// Run after changing plugins or additional fields:
//
//   npx esbuild scripts/auth-schema.ts --bundle --platform=node --format=esm --packages=external \
//     --outfile=node_modules/.cache/auth-schema.mjs && node node_modules/.cache/auth-schema.mjs > migrations/0001_auth.sql
//
// Only for a fresh database: a later schema change needs a new numbered migration.
import Database from 'better-sqlite3';
import { getMigrations } from 'better-auth/db/migration';
import { buildAuthOptions } from '../packages/platform/src/control/auth/index';
import type { Env } from '../packages/platform/src/control/env';

// Every provider enabled, so no plugin's tables or columns are left out. Values are dummies.
const env = {
  APP_ORIGIN: 'https://app.example.com',
  BETTER_AUTH_SECRET: 'schema-generation-only-not-a-real-secret-0123456789',
  BLIND_INDEX_KEY: btoa('0'.repeat(32)),
  GOOGLE_CLIENT_ID: 'x',
  GOOGLE_CLIENT_SECRET: 'x',
  MICROSOFT_CLIENT_ID: 'x',
  MICROSOFT_CLIENT_SECRET: 'x',
} as Env;

const options = buildAuthOptions(env, new Database(':memory:') as never);
const { compileMigrations } = await getMigrations(options as Parameters<typeof getMigrations>[0]);
// "user"."email" holds ciphertext with a random IV, so a unique constraint on it means nothing;
// uniqueness moves to the blind index below.
const sql = (await compileMigrations()).replace('"email" text not null unique', '"email" text not null');
if (/"email" text not null unique/.test(sql)) throw new Error('unexpected schema shape');

// Our columns on Better Auth tables: blind indexes the adapter wrapper (auth/database.ts) fills
// and looks up by, since the plaintext columns hold ciphertext (security.md, D49).
const ours = `
-- Blind indexes maintained by the adapter wrapper (src/control/auth/database.ts).
alter table "user" add column "emailIndex" text;
create unique index "user_emailIndex_idx" on "user" ("emailIndex");
alter table "invitation" add column "emailIndex" text;
create index "invitation_emailIndex_idx" on "invitation" ("emailIndex");
alter table "ssoProvider" add column "domainIndex" text;
create index "ssoProvider_domainIndex_idx" on "ssoProvider" ("domainIndex");
`;

process.stdout.write(
  `-- Better Auth tables (default names, camelCase columns), generated by scripts/auth-schema.ts.\n` +
    `-- Do not edit by hand; see docs/development.md "Migrations".\n` +
    sql.replace(/;\s*/g, ';\n') +
    ours,
);
